"""chem_retro: single-step disconnections from a curated template set.

Every template is a reaction SMARTS written in the forward direction; the
disconnection is its reverse, applied with RunReactants. Depth 2 is offered as a
search, not as a synthesis plan: it is exhaustive enough to be useful on teaching
molecules and would be silly on a natural product.
"""
from __future__ import annotations

import itertools

from . import mol as molmod

# name, disconnection SMARTS written in the RETRO direction (target >> precursors),
# priority, note. Writing them retro-side up front avoids the flip: a forward
# "acid + alcohol >> ester" loses a water, so its reverse needs two molecules and
# cannot be applied to one target. Unmapped product atoms (the water/chloride
# that condenses out) are regenerated by RDKit.
TEMPLATES = [
    ("酯化", "[#6:4][CX3:1](=[OX1:2])[OX2:3][#6:5]"
             ">>[#6:4][CX3:1](=[OX1:2])[OX2H1].[#6:5][OX2H1]",
     1, "断酯键：羧酸 + 醇"),
    ("酰胺化", "[#6:4][CX3:1](=[OX1:2])[NX3:3][#6:5]"
               ">>[#6:4][CX3:1](=[OX1:2])[OX2H1].[NX3:3][#6:5]",
     1, "断酰胺键：羧酸（或酰氯）+ 胺"),
    ("Williamson 醚", "[#6:4][OX2:3][CX4:5]>>[#6:4][OX2H1].[CX4:5][Cl]",
     2, "断醚键：醇 + 卤代烃"),
    ("Suzuki 联芳", "[c:1]!@[c:2]>>[c:1][Br].[c:2]B(O)O",
     2, "断联芳键：芳基溴 + 芳基硼酸"),
    ("格氏加成", "[CX4:1]([OH1])[#6:2]>>[CX3:1]=O.[#6:2][Mg]Br",
     3, "断 C-C：酮/醛 + 格氏试剂"),
    ("还原胺化", "[CX4H2:1][NX3H1:2][#6:3]>>[CX3H1:1]=O.[NX3H2:2][#6:3]",
     3, "断 N-CH2：醛 + 伯胺"),
    ("Wittig 烯化", "[CX3H1:1]=[CX3H1:2]>>[CX3H1:1]=O.[CX3H1:2]P",
     3, "断 C=C：醛 + 磷叶立德（膦部分为近似表示）"),
    ("Claisen 缩合", "[CX3:1](=O)[CX4H2:2][CX3:3](=O)>>[CX3:1](=O)[CX4H3:2].[CX3:3](=O)OCC",
     3, "断 α-C：酯 + 酯"),
    ("Aldol", "[CX3:1](=O)[CX4H1:2][CX4H1:3]([OH1])>>[CX3:1]=O.[CX3:3]=O",
     4, "断 β-C：两个羰基化合物"),
    ("Diels-Alder", "[CX4H1:1]1[CX4H1:2][CX4H1:3][CX4H1:4][CX4H1:5][CX4H1:6]1"
                    ">>[CX3:1]=[CX3:2].[CX3:3]=[CX3:4]",
     5, "断环己烯：二烯 + 亲双烯体"),
    ("硝化", "[c:1][N+](=O)[O-]>>[cH:1]", 5, "断 C-N：芳环硝化"),
    ("磺化", "[c:1]S(=O)(=O)O>>[cH:1]", 5, "断 C-S：芳环磺化"),
    ("芳环卤代", "[c:1][Cl,Br,I]>>[cH:1]", 5, "断 C-X：芳环亲电卤代"),
]


def _reactions():
    from rdkit.Chem import AllChem
    prepared = []
    for name, retro_smarts, priority, note in TEMPLATES:
        if ">>" not in retro_smarts:
            continue
        try:
            reaction = AllChem.ReactionFromSmarts(retro_smarts)
        except Exception:  # noqa: BLE001
            continue
        # A retro step must consume exactly one molecule; a two-reactant reverse
        # template cannot be applied to a single target and raised at runtime.
        if reaction.GetNumReactantTemplates() != 1:
            continue
        prepared.append((name, reaction, priority, note))
    return prepared


def _one_step(m, name, reaction, note, limit=6):
    from rdkit import Chem
    products = reaction.RunReactants((m,))
    found = []
    seen = set()
    for product in products:
        try:
            combined = product[0] if len(product) == 1 else None
            if combined is None:
                combined = Chem.CombineMols(product[0], product[1])
                for extra in product[2:]:
                    combined = Chem.CombineMols(combined, extra)
            fragments = [frag for frag in Chem.GetMolFrags(combined, asMols=True, sanitizeFrags=False)]
        except Exception:  # noqa: BLE001
            continue
        cleaned = []
        for fragment in fragments:
            try:
                Chem.SanitizeMol(fragment)
            except Exception:  # noqa: BLE001
                continue
            if fragment.GetNumAtoms() == 0:
                continue
            try:
                cleaned.append(molmod.parse_struct(Chem.MolToSmiles(fragment)))
            except molmod.MolError:
                continue
        if not cleaned:
            continue
        key = tuple(sorted(molmod.inchikey(f) for f in cleaned))
        if key in seen:
            continue
        seen.add(key)
        found.append({"precursors": [molmod.canonical(f) for f in cleaned],
                      "precursorInchikeys": list(key),
                      "formulas": [molmod.formula(f) for f in cleaned],
                      "template": name, "note": note})
        if len(found) >= limit:
            break
    return found


def _search(payload):
    smiles = payload.get("smiles") or payload.get("target") or ""
    if not smiles:
        return {"ok": False, "failure": {"code": "missing-input", "message": "需要 smiles（目标分子）"}}
    depth = int(payload.get("depth") or 1)
    depth = 1 if depth < 1 else (2 if depth > 2 else depth)
    limit = int(payload.get("limit") or 8)
    m = molmod.parse_struct(smiles)

    reactions = _reactions()
    nodes = [{"target": molmod.canonical(m), "inchikey": molmod.inchikey(m), "depth": 0,
              "path": [], "parents": []}]
    frontier = [(m, [])]
    for level in range(1, depth + 1):
        next_frontier = []
        for mol, path in frontier:
            for name, reaction, priority, note in reactions:
                for option in _one_step(mol, name, reaction, note, limit=limit):
                    node = {"target": molmod.canonical(mol), "depth": level,
                            "template": option["template"], "note": option["note"],
                            "precursors": option["precursors"],
                            "precursorInchikeys": option["precursorInchikeys"],
                            "formulas": option["formulas"],
                            "route": path + [option["template"]]}
                    nodes.append(node)
                    if level < depth:
                        for text in option["precursors"]:
                            try:
                                next_frontier.append((molmod.parse_struct(text),
                                                      path + [option["template"]]))
                            except molmod.MolError:
                                continue
        frontier = next_frontier[:40]
        if not frontier:
            break

    first_level = [n for n in nodes if n.get("depth") == 1]
    deduped, seen = [], set()
    for node in first_level:
        key = tuple(node["precursorInchikeys"])
        if key in seen:
            continue
        seen.add(key)
        deduped.append(node)
    return {"ok": True, "channel": "template-library",
            "data": {"target": molmod.canonical(m), "targetFormula": molmod.formula(m),
                     "depth": depth, "templatesTried": len(reactions),
                     "disconnections": len(deduped), "routes": deduped,
                     "nodes": nodes if depth > 1 else [],
                     "nodesExplored": len(nodes)},
            "warnings": ([] if deduped else
                         ["模板库里没有命中：这批模板只覆盖常见教学反应，不是全合成搜索"]) + (
                         ["depth 2 是启发式搜索，最多展开 40 个节点，可能漏解"] if depth > 1 else []),
            "evidence": {"templates": [t[0] for t in TEMPLATES],
                         "engine": "RDKit RunReactants on retro-direction SMARTS"}}


def handle(payload):
    action = (payload.get("action") or "search").strip().lower()
    if action in ("search", "retro", "plan"):
        try:
            return _search(payload)
        except molmod.MolError as exc:
            return {"ok": False, "failure": {"code": exc.code, "message": exc.message,
                                            "hint": exc.hint}}
    if action == "templates":
        return {"ok": True, "channel": "template-library",
                "data": {"count": len(TEMPLATES),
                         "templates": [{"name": n, "priority": p, "note": note,
                                        "smarts": s} for n, s, p, note in TEMPLATES]}}
    return {"ok": False, "failure": {"code": "unknown-action", "message": "不认识的 action：" + action,
                                    "hint": "search | templates"}}
